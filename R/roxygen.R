## The roclet for `@type` annotations. It writes the annotations to `inst/TYR`,
## the file that contractr reads when R loads the package. Write one tag for
## each overload. The type of a function is the intersection of the arrows of
## its tags:
##
##   #' @type (x: dbl) -> dbl
##   #' @type (x: chr) -> chr
##   f <- function(x) ...

TYR_HEADER <- "# Generated by contractr::type_roclet from @type annotations: do not edit by hand"

#' Write the `@type` annotations to `inst/TYR`
#'
#' A roclet. To use it, add `contractr::type_roclet` to the roclets of the
#' package. For example, put this line in the DESCRIPTION file:
#'
#' `Roxygen: list(roclets = c("collate", "namespace", "rd", "contractr::type_roclet"))`
#'
#' The roclet writes each `#' @type <signature>` annotation of a function as a
#' `#| pkg::name : <signature>` line of `inst/TYR`. When R loads the package,
#' contractr monitors its calls (see [set_autoinject()]). The roclet does not
#' change an `inst/TYR` file that it did not write, for example a file from
#' `tyr --typedecl`.
#'
#' @export
type_roclet <- function() {
    roxygen2::roclet("type")
}

#' @exportS3Method roxygen2::roxy_tag_parse
roxy_tag_parse.roxy_tag_type <- function(x) {
    ## A signature can continue on more than one line.
    signature <- trimws(gsub("[[:space:]]*\n[[:space:]]*", " ", x$raw))
    if (is.null(tyr_split_signature(signature))) {
        roxygen2::roxy_tag_warning(x, "not a signature `(params) -> result`")
        return(NULL)
    }
    x$val <- signature
    x
}

#' @exportS3Method roxygen2::roclet_process
roclet_process.roclet_type <- function(x, blocks, env, base_path) {
    signatures <- list()
    for (block in blocks) {
        tags <- roxygen2::block_get_tags(block, "type")
        if (!length(tags)) next
        if (!inherits(block$object, "function")) {
            roxygen2::roxy_tag_warning(tags[[1L]], "@type annotates something that is not a function")
            next
        }
        name <- block$object$alias
        signatures[[name]] <- c(signatures[[name]],
                                vapply(tags, function(tag) tag$val, character(1)))
    }
    signatures
}

#' @exportS3Method roxygen2::roclet_output
roclet_output.roclet_type <- function(x, results, base_path, ...) {
    path <- file.path(base_path, "inst", "TYR")
    if (file.exists(path) &&
        !identical(readLines(path, n = 1L, warn = FALSE), TYR_HEADER)) {
        warning("contractr: not overwriting ", path,
                ", which type_roclet did not write", call. = FALSE)
        return(invisible(NULL))
    }
    if (!length(results)) {
        unlink(path)
        return(invisible(NULL))
    }

    package <- read.dcf(file.path(base_path, "DESCRIPTION"), fields = "Package")[[1L]]
    lines <- character(0)
    for (name in names(results)) {
        spelled <- tyr_spell(name)
        if (is.na(spelled)) {
            warning("contractr: a #| declaration cannot spell the name `", name,
                    "`, its @type is left out", call. = FALSE)
            next
        }
        lines <- c(lines, sprintf("#| %s::%s : %s", package, spelled, results[[name]]))
    }
    dir.create(dirname(path), showWarnings = FALSE)
    writeLines(c(TYR_HEADER, lines), path)
    message("Writing inst/TYR")
    invisible(path)
}

## Returns a name as a `#|` declaration writes it, with the rules of tyr
## (`lib/typedecl.ml`). An identifier stays the same. An operator goes in
## parentheses. Returns `NA` for other names.
tyr_spell <- function(name) {
    if (grepl("^[a-zA-Z_.][]a-zA-Z0-9_'?!+[$@<>.-]*$", name)) return(name)
    if (grepl("^([][+$@<>:=*%/|&!^~-]+|%[^%]*%)$", name)) return(paste0("(", name, ")"))
    NA_character_
}
